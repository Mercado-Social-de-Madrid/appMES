from django.core.management.base import BaseCommand
from django.db import transaction
from django.db.models import Q

from core.models import Node
from market.models import Account


class Command(BaseCommand):
    help = 'Assign an autogenerated member id to the accounts without one (markets without an external CRM only)'

    def add_arguments(self, parser):
        parser.add_argument('-n', '--node', type=int, help='Node Id (all the markets without an external CRM by default)')
        parser.add_argument('--dry-run', action='store_true', help='Show the accounts that would be updated, without saving')

    def handle(self, *args, **options):
        nodes = Node.objects.filter(has_linked_crm=False)
        if options['node']:
            nodes = nodes.filter(pk=options['node'])
            if not nodes.exists():
                self.stderr.write(f"Node {options['node']} not found or it uses an external CRM")
                return

        for node in nodes:
            accounts = Account.objects.filter(node=node).filter(Q(member_id__isnull=True) | Q(member_id='')) \
                .order_by('registration_date', 'last_updated')
            self.stdout.write(f'{node.name}: {accounts.count()} accounts without member id')

            for account in accounts:
                if options['dry_run']:
                    self.stdout.write(f'  [dry-run] {account.display_name} ({account.email})')
                    continue
                with transaction.atomic():
                    account.member_id = Account.generate_member_id(node)
                    account.save(update_fields=['member_id'])
                self.stdout.write(f'  {account.member_id}: {account.display_name} ({account.email})')
